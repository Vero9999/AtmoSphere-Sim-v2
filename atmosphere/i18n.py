DEFAULT_LANG = "id"


def fmt(x: float, nd: int = 0, lang: str = DEFAULT_LANG) -> str:
    """Format angka: 1.234,5 (id) atau 1,234.5 (en)."""
    s = f"{x:,.{nd}f}"
    if lang == "id":
        s = s.replace(",", "X").replace(".", ",").replace("X", ".")
    return s


